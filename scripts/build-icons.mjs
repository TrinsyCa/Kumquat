// Generates src/renderer/icons.js from lucide-static so only the icons we use get shipped.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const dir = path.join(path.dirname(require.resolve('lucide-static/package.json')), 'icons');

// Kumquat icon name → Lucide icon name
const ICONS = {
  compress: 'shrink', resize: 'scaling', 'rotate-cw': 'rotate-cw', 'rotate-ccw': 'rotate-ccw', flip: 'flip-horizontal-2',
  contrast: 'contrast', crop: 'crop', shield: 'shield-off', merge: 'merge', scissors: 'scissors', split: 'split',
  volume: 'volume-2', gauge: 'gauge', image: 'image', mute: 'volume-x', pages: 'files', trash: 'trash-2', hash: 'hash',
  stamp: 'stamp', unzip: 'package-open', archive: 'archive', fingerprint: 'fingerprint', share: 'smartphone', float: 'pin',
  copy: 'copy', move: 'folder-input', 'copy-to': 'folder-output', link: 'link', terminal: 'square-terminal',
  reveal: 'folder-open', settings: 'settings', close: 'x', check: 'check', alert: 'circle-alert', files: 'file-stack',
  convert: 'refresh-cw', tools: 'wrench', actions: 'zap', open: 'external-link', plus: 'plus',
};

const out = {};
for (const [name, lucide] of Object.entries(ICONS)) {
  const svg = fs.readFileSync(path.join(dir, `${lucide}.svg`), 'utf8');
  out[name] = svg.replace(/<!--[\s\S]*?-->/, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].replace(/\s+/g, ' ').trim();
}
const file = path.join(import.meta.dirname, '..', 'src', 'renderer', 'icons.js');
fs.writeFileSync(file, `// Generated by scripts/build-icons.mjs from Lucide (ISC License, https://lucide.dev). Do not edit.\nexport const ICONS = ${JSON.stringify(out, null, 1)};\n\nexport function icon(name, size = 20) {\n  const body = ICONS[name] ?? ICONS.files;\n  return \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\${body}</svg>\`;\n}\n`);
console.log(`Wrote ${Object.keys(out).length} icons to ${file}`);
